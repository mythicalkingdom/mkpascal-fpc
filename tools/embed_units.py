#!/usr/bin/env python3
"""Regenerates src/mkp_stdunits.pas from units/*.PAS (run `make units`)."""
import glob, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['{ generated by tools/embed_units.py from units/*.PAS - do not edit }',
       'unit mkp_stdunits;', '', 'interface', '',
       'function StdUnitSource(const Name: string; out Text: string): Boolean;', '',
       'implementation', '', 'uses SysUtils;', '']
names = []
for path in sorted(glob.glob(os.path.join(root, 'units', '*.PAS'))):
    n = os.path.splitext(os.path.basename(path))[0]
    names.append(n)
    out.append('function Src_%s: string;' % n)
    out.append('begin')
    out.append("  Result := ''")
    for line in open(path, encoding='latin-1').read().split('\n'):
        out.append("    + '%s' + #10" % line.rstrip('\r').replace("'", "''"))
    out.append('  ;')
    out.append('end;')
    out.append('')
out.append('function StdUnitSource(const Name: string; out Text: string): Boolean;')
out.append('begin')
out.append('  Result := True;')
for n in names:
    out.append("  if SameText(Name, '%s') then Text := Src_%s else" % (n, n))
out.append('  begin Text := \'\'; Result := False; end;')
out.append('end;')
out.append('')
out.append('end.')
open(os.path.join(root, 'src', 'mkp_stdunits.pas'), 'w', encoding='latin-1').write('\n'.join(out) + '\n')
